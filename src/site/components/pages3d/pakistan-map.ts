const CX = (46 + 694) / 2;
const CY = (105 + 639) / 2;
/** Source pixels → scene units (y up), `width` units across. */
export function toScene(x: number, y: number, width = 4.5): [number, number] {
  const s = width / (694 - 46);
  return [(x - CX) * s, -(y - CY) * s];
}

export function insidePk(x: number, y: number) {
  let inside = false;
  for (let i = 0, j = PK_OUTLINE.length - 1; i < PK_OUTLINE.length; j = i++) {
    const [xi, yi] = PK_OUTLINE[i];
    const [xj, yj] = PK_OUTLINE[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
